(function () {
  var books = window.ENC_BOOKS || [];

  function esc(s) {
    return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  /* the hover menu under "Major Project 1" */
  var menu = document.querySelector("[data-books-menu]");
  if (menu) {
    var html = '<a href="project1.html">All of it<span>The shelf</span></a>' +
               '<a href="https://docs.google.com/document/d/1u2y9YvxRmU-bmETA-_uA0fbf8Q7nnBEiwyMzqH2hSYU/edit?usp=sharing" target="_blank" rel="noopener">&#9733; Graded draft with comments<span>Google Doc</span></a>';
    books.forEach(function (b) {
      html += '<a href="' + esc(b.href) + '">' + esc(b.title) +
              '<span>' + esc(b.blurb) + '</span></a>';
    });
    menu.innerHTML = html;
  }

  /* the shelf on project1.html: each book with its text box beside it */
  var shelf = document.querySelector("[data-books-shelf]");
  if (shelf) {
    shelf.innerHTML = books.map(function (b) {
      var accent = 'style="--accent:var(--' + esc(b.accent) + ')"';
      var box = b.reflect
        ? '<div class="textbox reflectbox" ' + accent + '>' +
            '<h3>' + esc(b.title) + '</h3>' +
            '<p class="tags">' + (b.tags || []).map(function (t) {
              return '<strong>' + esc(t) + '</strong>';
            }).join(' &middot; ') + '</p>' +
            '<p>' + esc(b.reflect) + '</p>' +
          '</div>'
        : '';
      return '<div class="shelfrow">' +
               '<a class="shelfbook" href="' + esc(b.href) + '" ' + accent + '>' +
                 '<span class="shelfcover">' +
                   '<span class="cover-title">' + esc(b.title) + '</span>' +
                   '<hr class="cover-rule">' +
                   '<span class="cover-sub">Michael Wong &middot; ENC 1101</span>' +
                 '</span>' +
                 '<span class="shelfkicker">Read on this site</span>' +
                 '<span class="shelfdesc">' + esc(b.desc) + '</span>' +
                 '<span class="shelfcta">Open the book &rarr;</span>' +
               '</a>' +
               box +
             '</div>';
    }).join("");
  }
})();
